set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<EOSQL
CREATE ROLE "$APP_DB_USER" LOGIN PASSWORD '$APP_DB_PASSWORD'
  NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE "$MONITOR_DB_USER" LOGIN PASSWORD '$MONITOR_DB_PASSWORD'
  NOSUPERUSER NOCREATEDB NOCREATEROLE;

-- App: chỉ đọc/ghi dữ liệu, không DELETE, không DDL
GRANT CONNECT ON DATABASE "$POSTGRES_DB" TO "$APP_DB_USER", "$MONITOR_DB_USER";
GRANT USAGE ON SCHEMA public TO "$APP_DB_USER";
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA public TO "$APP_DB_USER";

-- Các bảng tạo sau script này: ứng dụng được phép đọc.
ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT SELECT ON TABLES TO "$APP_DB_USER";
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO "$APP_DB_USER";

-- Monitor: chỉ đọc thống kê
GRANT pg_monitor TO "$MONITOR_DB_USER";
EOSQL
